def database_from_url(raw_url: str) -> dict:
    parsed = urlparse(raw_url)
    if parsed.scheme in {"postgres", "postgresql"}:
        if not parsed.hostname or not parsed.path.strip("/"):
            raise ValueError("DATABASE_URL must include PostgreSQL host and database name")
        query = parse_qs(parsed.query)
        options = {key: values[-1] for key, values in query.items() if key in {"sslmode", "sslrootcert", "connect_timeout"}}
        return {
            "ENGINE": "django.db.backends.postgresql",
            "NAME": unquote(parsed.path.lstrip("/")),
            "USER": unquote(parsed.username or ""),
            "PASSWORD": unquote(parsed.password or ""),
            "HOST": parsed.hostname,
            "PORT": parsed.port or 5432,
            "OPTIONS": options,
        }
    if parsed.scheme == "sqlite":
        name = unquote(parsed.path.lstrip("/"))
        return {"ENGINE": "django.db.backends.sqlite3", "NAME": BASE_DIR / name if name else BASE_DIR / "db.sqlite3"}
    raise ValueError("DATABASE_URL must start with postgresql:// or sqlite:///")


